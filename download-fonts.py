#!/usr/bin/env python3
"""
Downloads the Cairo font from Google Fonts ONCE and stores it inside the project, so the site
no longer depends on fonts.googleapis.com / fonts.gstatic.com.

    python tools/download-fonts.py

What it does
  1. Fetches the Google Fonts CSS for Cairo (variable weights 200-1000) using a modern browser
     User-Agent, so Google answers with WOFF2 files split by script (arabic / latin / ...).
  2. Downloads the 'arabic' and 'latin' files into fonts/ as  cairo-arabic.woff2  and  cairo-latin.woff2
     (each one covers every weight, so two small files are enough).
  3. Writes fonts/fonts.css with the matching @font-face rules (family name 'CairoLocal').
  4. Edits index.html: removes the Google Fonts <link> tags (the blocks between the "google-fonts"
     marker comments) and preloads the Arabic font file instead. Run it again any time, it is idempotent.

After running it, commit fonts/, index.html. Only Python 3 is required (standard library only).

Options:   --css-url URL   use another CSS URL (used by the automated tests)
           --keep-google   do not touch index.html (keeps the Google Fonts links as a fallback)
"""
import argparse
import os
import re
import sys
import urllib.request

CSS_URL = "https://fonts.googleapis.com/css2?family=Cairo:wght@200..1000&display=swap"
USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
WANTED = ("arabic", "latin")          # latin-ext / vietnamese are not needed for this site

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "fonts")


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = resp.read()
    return data if binary else data.decode("utf-8")


def parse_blocks(css):
    """Returns {subset_name: (woff2_url, unicode_range)} from Google's '/* subset */ @font-face {...}' blocks."""
    blocks = {}
    for m in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", css, re.S):
        name, body = m.group(1), m.group(2)
        src = re.search(r"url\(([^)]+)\)", body)
        rng = re.search(r"unicode-range:\s*([^;]+);", body)
        if src and rng:
            blocks[name] = (src.group(1).strip("'\""), rng.group(1).strip())
    return blocks


def build_css(blocks):
    out = ["/* Generated by tools/download-fonts.py — self-hosted Cairo (variable, weights 200-1000) */"]
    for name in WANTED:
        url, rng = blocks[name]
        out.append(
            "@font-face {\n"
            "    font-family: 'CairoLocal';\n"
            "    font-style: normal;\n"
            "    font-weight: 200 1000;\n"
            "    font-display: swap;\n"
            f"    src: url('cairo-{name}.woff2') format('woff2');\n"
            f"    unicode-range: {rng};\n"
            "}"
        )
    return "\n".join(out) + "\n"


PRELOAD = '<link rel="preload" href="fonts/cairo-arabic.woff2" as="font" type="font/woff2" crossorigin>'


def patch_index():
    """Removes the Google Fonts tags (between the marker comments) and preloads the self-hosted Arabic font."""
    path = os.path.join(ROOT, "index.html")
    if not os.path.exists(path):
        print("  index.html not found, skipped")
        return
    with open(path, encoding="utf-8") as f:
        html = f.read()
    new = re.sub(r"[ \t]*<!-- google-fonts-css:start.*?google-fonts-css:end -->\n?", "", html, flags=re.S)
    new = re.sub(r"([ \t]*)<!-- google-fonts:start.*?google-fonts:end -->", r"\1" + PRELOAD.replace("\\", "\\\\"), new, flags=re.S)
    if new == html:
        print("  index.html already uses the self-hosted font (nothing to change)")
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)
    print("  index.html: Google Fonts links removed, self-hosted font preloaded")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--css-url", default=CSS_URL)
    ap.add_argument("--keep-google", action="store_true")
    args = ap.parse_args()

    print("Fetching", args.css_url)
    blocks = parse_blocks(fetch(args.css_url))
    missing = [n for n in WANTED if n not in blocks]
    if missing:
        sys.exit("Could not find these subsets in Google's CSS: " + ", ".join(missing) + " (found: " + ", ".join(blocks) + ")")

    os.makedirs(FONTS, exist_ok=True)
    for name in WANTED:
        data = fetch(blocks[name][0], binary=True)
        if data[:4] != b"wOF2":
            sys.exit(f"{name}: the downloaded file is not a WOFF2 font")
        path = os.path.join(FONTS, f"cairo-{name}.woff2")
        with open(path, "wb") as f:
            f.write(data)
        print(f"  saved {os.path.relpath(path, ROOT)}  ({len(data) / 1024:.0f} KB)")

    with open(os.path.join(FONTS, "fonts.css"), "w", encoding="utf-8") as f:
        f.write(build_css(blocks))
    print("  wrote fonts/fonts.css")

    if not args.keep_google:
        patch_index()
    print("Done. Commit fonts/ and index.html and the site will serve Cairo from your own domain.")


if __name__ == "__main__":
    main()
